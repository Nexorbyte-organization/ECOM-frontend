export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<Language>('en');

    useEffect(() => {
        const stored = localStorage.getItem('usher_lang') as Language;
        let preferred: Language = 'en';
        if (stored === 'en' || stored === 'ar' || stored === 'ar-eg') {
            preferred = stored;
        } else {
            // Default to arabic if browser prefers it or fallback to english
            const browserLang = navigator.language.split('-')[0];
            if (browserLang === 'ar') {
                preferred = 'ar';
            }
        }
        queueMicrotask(() => setLanguageState(preferred));
    }, []);

    const setLanguage = (lang: Language) => {
        localStorage.setItem('usher_lang', lang);
        setLanguageState(lang);
    };

    const dir: Direction = (language === 'ar' || language === 'ar-eg') ? 'rtl' : 'ltr';

    useEffect(() => {
        document.documentElement.dir = dir;
        document.documentElement.lang = language === 'ar-eg' ? 'ar-EG' : language;
    }, [language, dir]);

    const t = (key: string): string => {
        return translations[language]?.[key] || translations['ar']?.[key] || translations['en'][key] || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, dir, t }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const ctx = useContext(LanguageContext);
    if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
    return ctx;
}
